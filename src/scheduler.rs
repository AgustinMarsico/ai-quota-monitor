static STOP: AtomicBool = AtomicBool::new(false);
extern "C" fn stop(_: libc::c_int) {
    STOP.store(true, Ordering::Relaxed);
}
pub fn backoff(failures: u32, interval: u64, maximum: u64, retry: Option<u64>, seed: u64) -> u64 {
    let base = interval
        .saturating_mul(1u64 << failures.min(16))
        .min(maximum);
    let jitter = seed % (base / 10 + 1);
    base.saturating_add(jitter)
        .min(maximum)
        .max(retry.unwrap_or(0).min(i64::MAX as u64))
}
/// Return true only when the Go authentication method has actually changed.
/// Older snapshots did not store the method: infer it only from a recognized
/// successful request source, never from arbitrary error text or missing data.
fn go_auth_changed(p: &ProviderStatus, c: &ProviderConfig) -> bool {
    if c.provider != "opencode-go" {
        return false;
    }
    let previous = p.go_auth.or(match p.source.as_str() {
        "https://opencode.ai/zen/go/v1/usage" => Some(GoAuth::ApiKey),
        crate::providers::go::CONSOLE_USAGE_URL => Some(GoAuth::ConsoleOauth),
        _ => None,
    });
    previous.is_some_and(|method| method != c.go_auth)
}

/// A new authentication method should get its own first attempt and retry
/// sequence. Quotas, historical samples and alert deduplication stay intact.
fn clear_previous_auth_backoff(p: &mut ProviderStatus) {
    p.consecutive_failures = 0;
    p.next_attempt_at = 0;
}

/// Operational outcomes generated by actual requests (not by old cached errors).
/// Events never contain server messages, credentials, URLs or response bodies.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UpdateEvent {
    pub provider: String,
    pub profile: String,
    pub kind: UpdateEventKind,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum UpdateEventKind {
    AuthChanged {
        from: GoAuth,
        to: GoAuth,
    },
    Succeeded {
        recovered: bool,
    },
    Failed {
        cause: ErrorKind,
        failures: u32,
        next_attempt_at: i64,
    },
    SkippedBackoff {
        next_attempt_at: i64,
    },
}

/// Keeps the console log quiet between real requests. Debug-only skipped
/// attempts are emitted once for each distinct retry deadline.
#[derive(Default)]
pub struct EventLogger {
    debug: bool,
    last_skipped: HashMap<(String, String), i64>,
}

impl EventLogger {
    pub fn new(debug: bool) -> Self {
        Self {
            debug,
            last_skipped: HashMap::new(),
        }
    }

    pub fn format(&mut self, events: impl IntoIterator<Item = UpdateEvent>) -> Vec<String> {
        let mut output = Vec::new();
        for event in events {
            let key = (event.provider.clone(), event.profile.clone());
            match &event.kind {
                UpdateEventKind::SkippedBackoff { next_attempt_at } => {
                    if self.debug && self.last_skipped.get(&key) != Some(next_attempt_at) {
                        output.push(event.line());
                        self.last_skipped.insert(key, *next_attempt_at);
                    }
                }
                UpdateEventKind::Failed {
                    failures,
                    next_attempt_at,
                    ..
                } => {
                    self.last_skipped.remove(&key);
                    output.push(event.line());
                    if *failures == 1 {
                        output.push(format!(
                            "INFO provider={} profile={} event=backoff_started next_attempt_at={}",
                            event.provider, event.profile, next_attempt_at
                        ));
                    }
                }
                _ => {
                    self.last_skipped.remove(&key);
                    output.push(event.line());
                }
            }
        }
        output
    }
}

fn auth_label(method: GoAuth) -> &'static str {
    match method {
        GoAuth::ApiKey => "api_key",
        GoAuth::ConsoleOauth => "console_oauth",
    }
}

fn error_label(kind: &ErrorKind) -> &'static str {
    match kind {
        ErrorKind::Authentication => "authentication",
        ErrorKind::CredentialsMissing => "credentials_missing",
        ErrorKind::RateLimited => "rate_limited",
        ErrorKind::Network => "network",
        ErrorKind::InvalidResponse => "invalid_response",
        ErrorKind::Unavailable => "unavailable",
        ErrorKind::Internal => "internal",
    }
}

impl UpdateEvent {
    /// The message is assembled exclusively from validated provider/profile IDs,
    /// whitelisted labels, and numbers. Never log ProviderError.message.
    pub fn line(&self) -> String {
        let prefix = format!("provider={} profile={}", self.provider, self.profile);
        match &self.kind {
            UpdateEventKind::AuthChanged { from, to } => format!(
                "INFO {prefix} event=auth_changed from={} to={}",
                auth_label(*from), auth_label(*to)
            ),
            UpdateEventKind::Succeeded { recovered: true } => {
                format!("INFO {prefix} event=recovered")
            }
            UpdateEventKind::Succeeded { recovered: false } => {
                format!("INFO {prefix} event=query_succeeded")
            }
            UpdateEventKind::Failed { cause, failures, next_attempt_at } => format!(
                "WARN {prefix} event=query_failed cause={} failures={failures} next_attempt_at={next_attempt_at}",
                error_label(cause)
            ),
            UpdateEventKind::SkippedBackoff { next_attempt_at } => format!(
                "DEBUG {prefix} event=backoff_skipped next_attempt_at={next_attempt_at}"
            ),
        }
    }
}

fn apply_result(
    p: &mut crate::model::ProviderStatus,
    c: &crate::config::ProviderConfig,
    config: &Config,
    timestamp: i64,
    result: Result<Reading, ProviderError>,
) -> bool {
    p.last_attempt_at = Some(timestamp);
    if c.provider == "opencode-go" {
        p.go_auth = Some(c.go_auth);
    }
    let finished = now().max(timestamp);
    let success = match result {
        Ok(reading) => {
            p.quotas = reading.quotas;
            p.account = reading.account;
            p.model = reading.model;
            p.plan = reading.plan;
            p.source = reading.source;
            p.limitations = reading.limitations;
            p.last_success_at = Some(finished);
            p.error = None;
            p.consecutive_failures = 0;
            p.next_attempt_at = finished.saturating_add(c.interval_seconds as i64);
            true
        }
        Err(error) => {
            p.consecutive_failures = p.consecutive_failures.saturating_add(1);
            let interval = if matches!(
                error.kind,
                ErrorKind::Authentication | ErrorKind::CredentialsMissing
            ) {
                c.interval_seconds.max(600)
            } else {
                c.interval_seconds
            };
            p.next_attempt_at = finished.saturating_add(backoff(
                p.consecutive_failures,
                interval,
                config.max_backoff_seconds,
                error.retry_after_seconds,
                timestamp as u64,
            ) as i64);
            p.error = Some(error);
            false
        }
    };
    p.age_state(finished, config.stale_seconds);
    success
}
pub fn update_with<F>(
    config: &Config,
    loc: &Locations,
    provider: Option<&str>,
    manual: bool,
    timestamp: i64,
    fetch: F,
) -> Result<(Snapshot, bool), String>
where
    F: FnMut(&crate::config::ProviderConfig, i64) -> Result<Reading, ProviderError>,
{
    let (snapshot, failed, _) =
        update_with_events(config, loc, provider, manual, timestamp, fetch)?;
    Ok((snapshot, failed))
}

/// Same durable update as `update_with`, with a per-attempt diagnostic report.
/// The configured notification runtime is used and delivery errors never change
/// the monitoring result. Use `update_with_events_without_notifications` for a
/// persistence-only update.
pub fn update_with_events<F>(
    config: &Config,
    loc: &Locations,
    provider: Option<&str>,
    manual: bool,
    timestamp: i64,
    fetch: F,
) -> Result<(Snapshot, bool, Vec<UpdateEvent>), String>
where
    F: FnMut(&crate::config::ProviderConfig, i64) -> Result<Reading, ProviderError>,
{
    let runtime = crate::notifications::runtime::Runtime::from_config(config);
    let result = update_with_events_runtime(
        config,
        loc,
        provider,
        manual,
        timestamp,
        fetch,
        Some(&runtime),
    );
    runtime.flush_for(Duration::from_secs(2));
    result
}

/// Performs the durable update and returns events without starting notification
/// workers or delivering alerts. Intended for callers that explicitly own delivery.
pub fn update_with_events_without_notifications<F>(
    config: &Config,
    loc: &Locations,
    provider: Option<&str>,
    manual: bool,
    timestamp: i64,
    fetch: F,
) -> Result<(Snapshot, bool, Vec<UpdateEvent>), String>
where
    F: FnMut(&crate::config::ProviderConfig, i64) -> Result<Reading, ProviderError>,
{
    update_with_events_runtime(config, loc, provider, manual, timestamp, fetch, None)
}

fn update_with_events_runtime<F>(
    config: &Config,
    loc: &Locations,
    provider: Option<&str>,
    manual: bool,
    timestamp: i64,
    mut fetch: F,
    runtime: Option<&crate::notifications::runtime::Runtime>,
) -> Result<(Snapshot, bool, Vec<UpdateEvent>), String>
where
    F: FnMut(&crate::config::ProviderConfig, i64) -> Result<Reading, ProviderError>,
{
    let lock = storage::writer_lock(loc)?;
    let mut db = storage::open(loc)?;
    let mut snapshot = storage::durable(&db, config)?;
    let mut successes = vec![];
    let mut attempts = vec![];
    let mut failed = false;
    let mut attempted = false;
    let mut events = vec![];
    for c in config
        .providers
        .iter()
        .filter(|c| c.enabled && provider.is_none_or(|id| c.provider == id))
    {
        if STOP.load(Ordering::Relaxed) {
            break;
        }
        let p = snapshot
            .providers
            .iter_mut()
            .find(|p| p.provider == c.provider && p.profile == c.profile)
            .ok_or("Missing profile")?;
        // A changed Go authentication method invalidates only that provider's
        // old retry delay. Normal/manual refreshes still respect error backoff.
        let auth_changed = go_auth_changed(p, c);
        if !auth_changed && p.next_attempt_at > timestamp && (!manual || p.error.is_some()) {
            // Ordinary polling between successful reads is not "backoff".
            if p.error.is_some() {
                events.push(UpdateEvent {
                    provider: c.provider.clone(),
                    profile: c.profile.clone(),
                    kind: UpdateEventKind::SkippedBackoff {
                        next_attempt_at: p.next_attempt_at,
                    },
                });
            }
            continue;
        }
        if auth_changed {
            // Inferred only from a known source or a recorded auth marker.
            let previous = p.go_auth.or(match p.source.as_str() {
                "https://opencode.ai/zen/go/v1/usage" => Some(GoAuth::ApiKey),
                crate::providers::go::CONSOLE_USAGE_URL => Some(GoAuth::ConsoleOauth),
                _ => None,
            });
            if let Some(from) = previous {
                events.push(UpdateEvent {
                    provider: c.provider.clone(),
                    profile: c.profile.clone(),
                    kind: UpdateEventKind::AuthChanged {
                        from,
                        to: c.go_auth,
                    },
                });
            }
            clear_previous_auth_backoff(p);
        }
        attempted = true;
        let recovered = p.error.is_some();
        if apply_result(p, c, config, timestamp, fetch(c, timestamp)) {
            successes.push((p.provider.clone(), p.profile.clone()));
            attempts.push(storage::Attempt {
                provider: c.provider.clone(),
                profile: c.profile.clone(),
                at: timestamp,
                succeeded: true,
                auth_changed,
            });
            events.push(UpdateEvent {
                provider: c.provider.clone(),
                profile: c.profile.clone(),
                kind: UpdateEventKind::Succeeded { recovered },
            });
        } else {
            failed = true;
            attempts.push(storage::Attempt {
                provider: c.provider.clone(),
                profile: c.profile.clone(),
                at: timestamp,
                succeeded: false,
                auth_changed,
            });
            let error = p.error.as_ref().expect("failed request sets an error");
            events.push(UpdateEvent {
                provider: c.provider.clone(),
                profile: c.profile.clone(),
                kind: UpdateEventKind::Failed {
                    cause: error.kind.clone(),
                    failures: p.consecutive_failures,
                    next_attempt_at: p.next_attempt_at,
                },
            });
        }
    }
    if !attempted {
        if storage::read_cache(&loc.cache)
            .map_or(true, |cache| cache.generated_at != snapshot.generated_at)
        {
            storage::atomic_write(
                &loc.cache,
                &serde_json::to_vec(&snapshot).map_err(|_| "Cannot serialize recovered state")?,
            )?;
        }
        return Ok((snapshot, false, events));
    }
    snapshot.generated_at = now().max(timestamp);
    let notifications =
        storage::save_with_attempts(&mut db, loc, &snapshot, &successes, &attempts, config)?;
    drop(db);
    drop(lock);
    if let Some(runtime) = runtime {
        for notification in notifications {
            runtime.submit(notification);
        }
    }
    Ok((snapshot, failed, events))
}
pub fn refresh(
    config: &Config,
    loc: &Locations,
    provider: Option<&str>,
    manual: bool,
) -> Result<(Snapshot, bool), String> {
    let runtime = crate::notifications::runtime::Runtime::from_config(config);
    let result = update_with_events_runtime(
        config,
        loc,
        provider,
        manual,
        now(),
        providers::fetch,
        Some(&runtime),
    )
    .map(|(snapshot, failed, _)| (snapshot, failed));
    runtime.flush_for(Duration::from_secs(2));
    result
}
pub fn check(
    config: &Config,
    loc: &Locations,
    provider: Option<&str>,
) -> Result<(Snapshot, bool), String> {
    let _lock = storage::existing_writer_lock(loc)?;
    let previous = if loc.cache.exists() {
        Some(storage::read_cache(&loc.cache)?)
    } else {
        None
    };
    let mut snapshot = storage::empty(config);
    let mut failed = false;
    for c in config
        .providers
        .iter()
        .filter(|c| c.enabled && provider.is_none_or(|id| c.provider == id))
    {
        let p = snapshot
            .providers
            .iter_mut()
            .find(|p| p.provider == c.provider && p.profile == c.profile)
            .ok_or("Missing profile")?;
        if let Some(old) = previous.as_ref().and_then(|s| {
            s.providers
                .iter()
                .find(|p| p.provider == c.provider && p.profile == c.profile)
        }) {
            *p = old.clone();
        }
        let auth_changed = go_auth_changed(p, c);
        if !auth_changed && p.error.is_some() && p.next_attempt_at > now() {
            failed = true;
            continue;
        }
        if auth_changed {
            clear_previous_auth_backoff(p);
        }
        let timestamp = now();
        let result =
            if c.provider == "opencode-go" && c.go_auth == crate::config::GoAuth::ConsoleOauth {
                providers::go_oauth::fetch(c, true)
            } else {
                providers::fetch(c, timestamp)
            };
        failed |= !apply_result(p, c, config, timestamp, result);
    }
    snapshot.generated_at = now();
    Ok((snapshot, failed))
}
pub fn daemon(config: &Config, loc: &Locations) -> Result<(), String> {
    storage::private_dir(&loc.state)?;
    let daemon_lock = std::fs::OpenOptions::new()
        .read(true)
        .write(true)
        .create(true)
        .truncate(false)
        .open(loc.state.join("daemon.lock"))
        .map_err(|_| "Cannot open daemon lock")?;
    daemon_lock
        .try_lock()
        .map_err(|_| "Daemon already running")?;
    // SAFETY: handler only stores an atomic flag; no allocation or I/O in signal context.
    unsafe {
        libc::signal(libc::SIGTERM, stop as *const () as libc::sighandler_t);
        libc::signal(libc::SIGINT, stop as *const () as libc::sighandler_t);
    }
    eprintln!(
        "ai-quota daemon started; {} enabled profiles",
        config.providers.iter().filter(|c| c.enabled).count()
    );
    // Default logs record only actual requests and transitions. Debug mode also
    // records the first skipped cycle per provider and retry deadline.
    let debug =
        std::env::var("AI_QUOTA_LOG_LEVEL").is_ok_and(|value| value.eq_ignore_ascii_case("debug"));
    let mut logger = EventLogger::new(debug);
    let mut last_monitor_error: Option<(String, i64)> = None;
    let runtime = crate::notifications::runtime::Runtime::from_config(config);
    while !STOP.load(Ordering::Relaxed) {
        match update_with_events_runtime(
            config,
            loc,
            None,
            false,
            now(),
            providers::fetch,
            Some(&runtime),
        )
        .map(|(_, _, events)| events)
        {
            Ok(events) => {
                if last_monitor_error.take().is_some() {
                    eprintln!("INFO event=storage_recovered");
                }
                for line in logger.format(events) {
                    eprintln!("{line}");
                }
            }
            Err(error) => {
                // Persistent disk failures should remain visible without spamming
                // journald every five seconds. Messages originate in our own code.
                let current = now();
                let log_again = last_monitor_error.as_ref().is_none_or(|(prior, at)| {
                    prior != &error || current.saturating_sub(*at) >= 300
                });
                if log_again {
                    eprintln!("WARN event=monitor_error detail={error}");
                    last_monitor_error = Some((error, current));
                }
            }
        }
        for _ in 0..5 {
            if STOP.load(Ordering::Relaxed) {
                break;
            }
            std::thread::sleep(Duration::from_secs(1));
        }
    }
    runtime.shutdown();
    Ok(())
}

#[cfg(test)]
mod notification_runtime_tests {
    use super::*;

    #[test]
    fn quota_update_succeeds_when_optional_worker_cannot_start() {
        let dir = tempfile::tempdir().unwrap();
        let loc = Locations {
            state: dir.path().join("state"),
            cache: dir.path().join("cache/status.json"),
            config: dir.path().join("config.json"),
        };
        std::fs::create_dir_all(&loc.state).unwrap();
        std::fs::create_dir_all(loc.cache.parent().unwrap()).unwrap();
        let mut config = Config::default();
        config.providers.truncate(1);
        config.notifications = true;
        config.notification_transports.desktop = true;
        let runtime =
            crate::notifications::runtime::Runtime::from_config_simulating_spawn_failure(&config);
        let result = update_with_events_runtime(
            &config,
            &loc,
            None,
            false,
            now(),
            |_, _| {
                Ok(Reading {
                    account: None,
                    model: None,
                    quotas: vec![crate::model::Quota::new(
                        "primary",
                        "5h".into(),
                        Some(300),
                        96.0,
                        None,
                    )
                    .unwrap()],
                    plan: None,
                    source: "test".into(),
                    limitations: vec![],
                })
            },
            Some(&runtime),
        )
        .unwrap();
        assert!(!result.1);
        assert_eq!(result.0.providers[0].quotas[0].used_percent, 96.0);
        assert!(runtime.workers_empty_for_test());
    }
}
